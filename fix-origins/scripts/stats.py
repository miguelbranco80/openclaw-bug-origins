#!/usr/bin/env python3
"""Compute every figure used in report.md from cases.jsonl, second_reads.jsonl and rechecks.jsonl.

Usage (from the repo root):
    python3 research/fix-origins/scripts/stats.py > research/fix-origins/stats.md
"""
import json
import math
import os
import re
import statistics
import subprocess
from collections import Counter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORIGINS = ["regression", "never-worked", "latent", "not-a-defect", "unclear"]


def load(name: str) -> list:
    path = os.path.join(ROOT, name)
    if not os.path.exists(path):
        return []
    with open(path) as f:
        return [json.loads(l) for l in f if l.strip()]


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, c - h), min(1.0, c + h))


def share(k: int, n: int) -> str:
    lo, hi = wilson(k, n)
    return f"{k}/{n} ({100 * k / n:.0f}%; 95% range {100 * lo:.0f}–{100 * hi:.0f} in 100)" if n else "0/0"


def table(counter: Counter, n: int, title: str) -> list:
    out = [f"| {title} | Count | Share |", "|---|---|---|"]
    for k, v in counter.most_common():
        out.append(f"| {k} | {v} | {100 * v / n:.0f}% |")
    return out + [""]


BASE_SINCE = "2026-09-03T00:00:00Z"  # the shallow graft; most causes fall after it
TIP = "e6b42e31bc1522b8596958fbdd85c394b23fca7b"


def prefix_of(subject: str) -> str:
    m = re.match(r"^\s*([A-Za-z]+)", subject)
    word = m.group(1).lower() if m else ""
    return word if word in {"feat", "fix", "refactor", "perf"} else "other"


def baseline(caused: list) -> list:
    """Compare causing commits with every first-parent commit since BASE_SINCE (same tip)."""
    raw = subprocess.run(["git", "log", "--first-parent", f"--since={BASE_SINCE}", "--no-renames",
                          "--format=\x01%an\x02%s", "--name-only", TIP], check=True, capture_output=True,
                         text=True, errors="replace", env={**os.environ, "GIT_NO_LAZY_FETCH": "1"}).stdout
    commits = []
    for block in raw.split("\x01")[1:]:
        lines = block.split("\n")
        author, subject = lines[0].split("\x02", 1)
        commits.append((author, prefix_of(subject), len([p for p in lines[1:] if p])))
    n = len(commits)
    after = [c for c in caused if c["cause"]["date"] >= BASE_SINCE[:10]]
    m = len(after)
    if not m:
        return []
    files = sorted(f for _, _, f in commits)
    cfiles = sorted(c["cause"]["files_changed"] for c in after)
    out = [f"## Causes compared with all commits (causes on or after {BASE_SINCE[:10]}, n = {m}; "
           f"baseline: {n} first-parent commits from {BASE_SINCE[:10]} to the tip)", "",
           f"- Median files changed: causes {statistics.median(cfiles):.0f}, all commits "
           f"{statistics.median(files):.0f}; over 100 files: causes {100 * sum(f > 100 for f in cfiles) / m:.0f}%, "
           f"all commits {100 * sum(f > 100 for f in files) / n:.1f}%; over 20 files: causes "
           f"{100 * sum(f > 20 for f in cfiles) / m:.0f}%, all commits {100 * sum(f > 20 for f in files) / n:.0f}%", "",
           "| Subject prefix | Share of causes | Share of all commits |", "|---|---|---|"]
    cp = Counter(c["cause"]["prefix"] for c in after)
    bp = Counter(p for _, p, _ in commits)
    for k in ("fix", "feat", "refactor", "perf", "other"):
        out.append(f"| {k} | {100 * cp[k] / m:.0f}% | {100 * bp[k] / n:.0f}% |")
    out += ["", "| Git author | Share of causes | Share of all commits |", "|---|---|---|"]
    ca = Counter(c["cause"]["author"] for c in after)
    ba = Counter(a for a, _, _ in commits)
    for k, v in ca.most_common(6):
        out.append(f"| {k} | {100 * v / m:.0f}% | {100 * ba[k] / n:.0f}% |")
    return out + [""]


def main() -> None:
    cases = sorted(load("cases.jsonl"), key=lambda c: c["rank"])
    seconds = {c["rank"]: c for c in load("second_reads.jsonl")}
    rechecks = load("rechecks.jsonl")
    n = len(cases)
    out = [f"# Computed figures (n = {n}, ranks {cases[0]['rank']}–{cases[-1]['rank']})" if n else "# no cases", "",
           "Generated by `scripts/stats.py`. Do not edit by hand.", ""]
    oc = Counter(c["origin"] for c in cases)
    out += ["## Origin split, all sampled fixes", ""]
    for o in ORIGINS:
        out.append(f"- {o}: {share(oc[o], n)}")
    defects = [c for c in cases if c["origin"] in {"regression", "never-worked", "latent"}]
    out += ["", f"Among fixes of real defects (regression + never-worked + latent, n = {len(defects)}):", ""]
    for o in ("regression", "never-worked", "latent"):
        out.append(f"- {o}: {share(oc[o], len(defects))}")

    vis = Counter(c["user_visible"] for c in cases)
    out += ["", "## User visibility", "", *[f"- {k}: {share(v, n)}" for k, v in vis.most_common()], ""]
    out += ["Origin by user visibility:", "", "| origin | yes | internal | unclear |", "|---|---|---|---|"]
    for o in ORIGINS:
        cc = Counter(c["user_visible"] for c in cases if c["origin"] == o)
        out.append(f"| {o} | {cc['yes']} | {cc['internal']} | {cc['unclear']} |")
    out.append("")

    caused = [c for c in cases if c["origin"] in {"regression", "never-worked"} and c["cause"]]
    for label, group in (("regression", [c for c in caused if c["origin"] == "regression"]),
                         ("never-worked", [c for c in caused if c["origin"] == "never-worked"]),
                         ("regression + never-worked", caused)):
        m = len(group)
        if not m:
            continue
        days = sorted(c["cause"]["days_to_fix"] for c in group)
        files = sorted(c["cause"]["files_changed"] for c in group)
        b = Counter()
        for d in days:
            b["under 1 day" if d < 1 else "1–7 days" if d <= 7 else "8–30 days" if d <= 30
              else "31–90 days" if d <= 90 else "over 90 days"] += 1
        conf = Counter(c["confidence"] for c in group)
        out += [f"## Causes: {label} (n = {m})", "",
                f"- Confidence: high {conf['high']}, medium {conf['medium']}, low {conf['low']}",
                f"- Days from cause to fix: median {statistics.median(days):.1f}, "
                f"quartiles {days[m // 4]:.1f} / {days[(3 * m) // 4]:.1f}; "
                + ", ".join(f"{k} {b[k]}" for k in ("under 1 day", "1–7 days", "8–30 days", "31–90 days",
                                                     "over 90 days")),
                f"- Cause committed inside the window (on or after 2026-11-01): "
                f"{sum(c['cause']['date'] >= '2026-11-01' for c in group)} of {m}",
                f"- Files changed by the cause: median {statistics.median(files):.0f}; "
                f"1–5 files {sum(f <= 5 for f in files)}, 6–20 {sum(5 < f <= 20 for f in files)}, "
                f"21–100 {sum(20 < f <= 100 for f in files)}, over 100 {sum(f > 100 for f in files)}",
                f"- Fix of a fix (cause titled fix): {share(sum(bool(c['fix_of_fix']) for c in group), m)}",
                f"- Fix names its cause (message or PR body): "
                f"{share(sum(bool(c['fix_names_cause']) for c in group), m)}",
                f"- Top blame candidate is the cause: {share(sum(bool(c['blame_agrees']) for c in group), m)}",
                f"- Cause is among the top five blame candidates: "
                f"{share(sum(bool(c['blame_in_top5']) for c in group), m)}",
                f"- Cause is an ancestor of the fix: {sum(c['cause']['is_ancestor_of_fix'] for c in group)} of {m}",
                ""]
        for lab, sub in (("fix names its cause", [c for c in group if c["fix_names_cause"]]),
                         ("fix does not name it", [c for c in group if not c["fix_names_cause"]])):
            if sub:
                d = [c["cause"]["days_to_fix"] for c in sub]
                out.append(f"- Days from cause to fix when the {lab}: n = {len(sub)}, median "
                           f"{statistics.median(d):.1f}, under 1 day {sum(x < 1 for x in d)}")
        recent = [c for c in group if c["cause"]["date"] >= BASE_SINCE[:10]]
        if recent:
            out.append(f"- Top blame candidate is the cause, causes on or after {BASE_SINCE[:10]} (visible to "
                       f"local blame): {share(sum(bool(c['blame_agrees']) for c in recent), len(recent))}")
        out.append("")
        hi = [c for c in group if c["confidence"] == "high"]
        if hi:
            out += [f"- High-confidence only (n = {len(hi)}): blame top-1 agrees "
                    f"{sum(bool(c['blame_agrees']) for c in hi)}, fix names cause "
                    f"{sum(bool(c['fix_names_cause']) for c in hi)}, fix of fix "
                    f"{sum(bool(c['fix_of_fix']) for c in hi)}", ""]
        out += table(Counter(c["cause"]["prefix"] for c in group), m, "Cause subject prefix")
        out += table(Counter(c["cause"]["author"] for c in group), m, "Cause git author")
        out += table(Counter(c["area"] for c in group), m, "Area")
        out += table(Counter(c["impact"] for c in group), m, "Impact")

    out += ["## All fixes: area and impact", ""]
    out += table(Counter(c["area"] for c in cases), n, "Area")
    out += table(Counter(c["impact"] for c in cases), n, "Impact")
    out += ["Area by origin:", "", "| area | " + " | ".join(ORIGINS) + " |", "|---" * (len(ORIGINS) + 1) + "|"]
    for a, _ in Counter(c["area"] for c in cases).most_common():
        out.append(f"| {a} | " + " | ".join(str(sum(c['area'] == a and c['origin'] == o for c in cases))
                                          for o in ORIGINS) + " |")
    out.append("")

    out += ["## Fix-side facts", "",
            f"- Fix adds or changes a test file: {share(sum(c['fix_adds_test'] for c in cases), n)}"]
    for o in ORIGINS:
        g = [c for c in cases if c["origin"] == o]
        if g:
            out.append(f"  - {o}: {sum(c['fix_adds_test'] for c in g)} of {len(g)}")
    out += [f"- Fix git author: " + ", ".join(f"{k} {v}" for k, v in
                                               Counter(c['fix_author'] for c in cases).most_common(6)), ""]

    out += baseline(caused)

    pairs = [(c, seconds[c["rank"]]) for c in cases if c["rank"] in seconds]
    if pairs:
        agree = sum(a["origin"] == b["origin"] for a, b in pairs)
        both = [(a, b) for a, b in pairs if a["cause_sha"] and b["cause_sha"]]
        same = sum(a["cause_sha"] == b["cause_sha"] for a, b in both)
        out += [f"## Reader agreement (n = {len(pairs)} fixes read twice)", "",
                f"- Same origin: {share(agree, len(pairs))}",
                f"- Both named a cause: {len(both)}; same causing commit: {same} of {len(both)}",
                f"- Defect vs not-a-defect agreement: "
                f"{sum((a['origin'] == 'not-a-defect') == (b['origin'] == 'not-a-defect') for a, b in pairs)} of "
                f"{len(pairs)}", "", "| rank | primary | second | primary cause | second cause |", "|---|---|---|---|---|"]
        for a, b in pairs:
            out.append(f"| {a['rank']} | {a['origin']} | {b['origin']} | {(a['cause_sha'] or '')[:10]} | "
                       f"{(b['cause_sha'] or '')[:10]} |")
        out.append("")
    if rechecks:
        out += [f"## Re-checks of high-confidence regressions in batch 1 (n = {len(rechecks)})", "",
                *[f"- {k}: {v}" for k, v in Counter(r['verdict'] for r in rechecks).most_common()], ""]
    print("\n".join(out))


if __name__ == "__main__":
    main()
